"""RQ6: enlarged-test and shared-index probes, under the identical frozen
protocol (cross-fitted selection on each run's own training chains).

Reads run_power_qwen3b.json (n_test=400) and run_shared_qwen3b.json
(--shared_index pooled corpus) when present; writes rq6.json and a quarantined
historical fragment.  The live RQ6 section also consumes the newer corpus,
TASR, and robustness analyses and is therefore maintained separately.
"""
import json
import pathlib

import numpy as np

import frozen_protocol as fp

MEAS = fp.MEAS
ART = pathlib.Path(__file__).resolve().parents[1]
MANU = ART / "manuscript"
if not MANU.exists():
    MANU = pathlib.Path(__file__).resolve().parents[2] / "manuscript"


def cell_or_none(tag):
    try:
        cell, d = fp.run_cell(tag)
    except FileNotFoundError:
        return None
    Q = d["per_q"]
    repeat_em = 100 * float(np.mean([
        r.get("answer_repeat_em", r.get("ent_em")) for r in Q]))
    repeat_s = float(np.mean([
        r.get("answer_repeat_searches", r.get("ent_searches")) for r in Q]))
    for k in ["_voi_em", "_react_em", "_stops"]:
        cell.pop(k)
    cell["answer_repeat"] = {"em": round(repeat_em, 1), "s": round(repeat_s, 2)}
    return cell


def main():
    out = {t: cell_or_none(t) for t in ["power_qwen3b", "shared_qwen3b"]}
    (MEAS / "rq6.json").write_text(json.dumps(out, indent=1, default=float))
    print(json.dumps({k: (v["voi_frozen"] if v else None)
                      for k, v in out.items()}, indent=1, default=float))

    p, s = out["power_qwen3b"], out["shared_qwen3b"]
    frag = ["% RQ6 body -- GENERATED by rq6_analysis.py from measured runs.",
            "Two probes push past the $n{=}140$ per-question-context design,",
            "both under the identical frozen protocol (thresholds cross-fitted",
            "on each run's own training chains)."]
    if p:
        d = p["paired_voi_vs_react"]
        frag.append(
            f"\\emph{{Enlarged test set.}} Replicating the anchor cell with "
            f"$n{{=}}400$ fresh test questions: frozen \\system\\ reaches "
            f"{p['voi_frozen']['em']:.1f}~EM at {p['voi_frozen']['s']:.2f} "
            f"searches ({p['voi_frozen']['save_pct']}\\% saving) versus "
            f"ReAct's {p['react']['em']:.1f} at 4.0; the paired difference "
            f"is ${d['mean_diff']:+.1f}$~EM with 95\\% CI "
            f"$[{d['ci95'][0]:.1f}, {d['ci95'][1]:.1f}]$---the CI half-width "
            f"shrinks from $\\pm$4.3 (at $n{{=}}140$) to $\\pm$1.9~EM, so "
            f"the design now excludes losses larger than "
            f"{-d['ci95'][0]:.2f}~EM while including zero. The "
            f"train-selected $B^{{*}}{{=}}3$ reaches "
            f"{p['bstar_frozen']['em']:.1f}~EM but needs "
            f"{p['bstar_frozen']['s']:.1f} searches to \\system's "
            f"{p['voi_frozen']['s']:.2f} (paired VoI$-$$B^{{*}}$ "
            f"${p['paired_voi_vs_bstar']['mean_diff']:+.1f}$ "
            f"$[{p['paired_voi_vs_bstar']['ci95'][0]:.1f}, "
            f"{p['paired_voi_vs_bstar']['ci95'][1]:.1f}]$), and the "
            f"sufficiency gate again barely stops "
            f"({p['suff_frozen']['s']:.2f} searches).")
    if s:
        d = s["paired_voi_vs_react"]
        frag.append(
            f"\\emph{{Shared cross-question index.}} Pooling one BM25 corpus "
            f"over all sampled questions' paragraphs makes distractors come "
            f"from \\emph{{other}} questions---retrieval noise the "
            f"per-question setting cannot exhibit---and the result is "
            f"honestly mixed. Frozen \\system\\ still saves "
            f"{s['voi_frozen']['save_pct']}\\% "
            f"({s['voi_frozen']['s']:.2f} vs.\\ 4.0 searches) but at "
            f"{s['voi_frozen']['em']:.1f}~EM versus ReAct's "
            f"{s['react']['em']:.1f}: a paired ${d['mean_diff']:+.1f}$~EM "
            f"(CI $[{d['ci95'][0]:.1f}, {d['ci95'][1]:.1f}]$), no longer "
            f"centred on zero. The answer-stability heuristic lands "
            f"nearby ({s['answer_repeat']['em']:.1f} at "
            f"{s['answer_repeat']['s']:.2f}), "
            f"and the train-selected $B^{{*}}{{=}}{s['b_star']}$ retains "
            f"more accuracy ({s['bstar_frozen']['em']:.1f} at 3.0). Early "
            f"stopping itself survives the noisier corpus, but the frozen "
            f"band rule transfers imperfectly---a more conservative "
            f"environment-specific selection (or richer critic features) "
            f"is needed there, and we state this as a limitation rather "
            f"than extrapolate the per-question-context result to open-web "
            f"retrieval.")
    historical = MANU / "sections" / "06-results-rq6-historical.tex"
    historical.write_text("\n".join(frag) + "\n")
    print(f"[wrote] {historical}")


if __name__ == "__main__":
    main()
